-- DB-01 section 8: 我的最愛 (favorite_stock). See docs/spec/DB-01-database-schema.md DEC-26/27.

CREATE TABLE favorite_stock (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_id   VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(50) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by VARCHAR(50) NOT NULL,
    CONSTRAINT pk_favorite_stock PRIMARY KEY (id),
    CONSTRAINT fk_favorite_stock_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id),
    CONSTRAINT uq_favorite_stock_stock_id UNIQUE (stock_id)
);
