-- Google Identity Services + 每位使用者獨立資料（TASK-052）。
-- V9 的明碼帳密只曾作為暫時性防護；正式改用 Google 後移除該憑證與永久 bearer token。
DROP TABLE IF EXISTS auth_session;
DROP TABLE IF EXISTS app_user;

CREATE TABLE app_user (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_subject        VARCHAR(255) NOT NULL UNIQUE,
    email                 VARCHAR(320) NOT NULL,
    display_name          VARCHAR(200),
    picture_url           TEXT,
    role                  VARCHAR(20) NOT NULL DEFAULT 'USER',
    enabled               BOOLEAN NOT NULL DEFAULT TRUE,
    legacy_data_claimed   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_user_role CHECK (role IN ('USER', 'ADMIN'))
);
CREATE UNIQUE INDEX uq_app_user_email_lower ON app_user (lower(email));

CREATE TABLE user_favorite_stock (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    stock_id    VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_favorite_stock UNIQUE (user_id, stock_id)
);

CREATE TABLE user_target_price_setting (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    stock_id            VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    investment_strategy TEXT,
    eps_avg_years       SMALLINT NOT NULL DEFAULT 5,
    bps_avg_years       SMALLINT NOT NULL DEFAULT 5,
    setting_note        TEXT,
    target_price_level  SMALLINT NOT NULL DEFAULT 3,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_target_price_setting UNIQUE (user_id, stock_id),
    CONSTRAINT ck_user_setting_eps_years CHECK (eps_avg_years IN (0, 3, 5, 10)),
    CONSTRAINT ck_user_setting_bps_years CHECK (bps_avg_years IN (0, 3, 5, 10)),
    CONSTRAINT ck_user_setting_target_level CHECK (target_price_level BETWEEN 1 AND 6)
);

CREATE TABLE user_stock_ai_suggestion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    stock_id        VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    suggestion_text TEXT,
    model_name      VARCHAR(50),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_stock_ai_suggestion UNIQUE (user_id, stock_id)
);

CREATE TABLE user_stock_health_profile (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    stock_id              VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    profile               TEXT,
    custom_note           TEXT,
    last_reviewed_quarter VARCHAR(10),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_stock_health_profile UNIQUE (user_id, stock_id)
);

CREATE TABLE user_stock_health_note (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    stock_id    VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    period      VARCHAR(10) NOT NULL,
    metric_key  VARCHAR(50) NOT NULL,
    note        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_stock_health_note UNIQUE (user_id, stock_id, period, metric_key)
);

CREATE TABLE user_stock_health_ai_suggestion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    stock_id        VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    suggestion_text TEXT,
    model_name      VARCHAR(50),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_stock_health_ai_suggestion UNIQUE (user_id, stock_id)
);

CREATE TABLE user_daily_usage (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES app_user (id) ON DELETE CASCADE,
    scope_key   VARCHAR(80) NOT NULL,
    usage_date  DATE NOT NULL,
    action      VARCHAR(50) NOT NULL,
    usage_count INTEGER NOT NULL DEFAULT 0,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_user_daily_usage_scope_action
    ON user_daily_usage (scope_key, usage_date, action);

CREATE TABLE shared_sync_state (
    stock_id       VARCHAR(10) NOT NULL REFERENCES stock (stock_id),
    action         VARCHAR(50) NOT NULL,
    last_success_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (stock_id, action)
);

-- Spring Session JDBC；登入狀態可跨 Render instance 重啟保留，30 天未使用才到期。
CREATE TABLE spring_session (
    primary_id               CHAR(36) NOT NULL PRIMARY KEY,
    session_id               CHAR(36) NOT NULL UNIQUE,
    creation_time            BIGINT NOT NULL,
    last_access_time         BIGINT NOT NULL,
    max_inactive_interval    INTEGER NOT NULL,
    expiry_time              BIGINT NOT NULL,
    principal_name           VARCHAR(320)
);
CREATE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36) NOT NULL REFERENCES spring_session (primary_id) ON DELETE CASCADE,
    attribute_name     VARCHAR(200) NOT NULL,
    attribute_bytes    BYTEA NOT NULL,
    PRIMARY KEY (session_primary_id, attribute_name)
);
