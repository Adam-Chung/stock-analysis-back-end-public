-- DB-01 §10: 企業體質檢視（SA-03）資料表。
-- See docs/spec/DB-01-database-schema.md §10, docs/agent/DECISIONS.md DEC-028~039.
--
-- 檢視項目（大項/細項/門檻/達標公式）本身不落地存表，寫死在後端程式碼
-- （com.adamchung.stockanalysis.healthcheck），這裡只有兩張表：不分季度的公司資訊，
-- 以及一張通用的「快照」表承接使用者每季手動輸入的數值與筆記。

CREATE TABLE stock_health_profile (
    stock_id              VARCHAR(10) NOT NULL,
    profile               TEXT,
    custom_note            TEXT,
    last_reviewed_quarter VARCHAR(10),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             VARCHAR(50) NOT NULL,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by             VARCHAR(50) NOT NULL,
    CONSTRAINT pk_stock_health_profile PRIMARY KEY (stock_id),
    CONSTRAINT fk_stock_health_profile_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id)
);

-- value 為 NUMERIC 而非文字（DEC-039）：SA-04 盤點結果幾乎所有細項本質上都是數字
-- （比率/百分比/倍數/金額/股數），布林類細項（如「10年來是否年年賺錢」）以 1/0 存。
-- 達標狀態不落地存，永遠在讀取當下依 metric_key 對應的程式碼門檻即時計算。
-- quarter 一般情況存 'YYYYQ#'（如 '2024Q4'）；銀行模板「月營收」相關 metric_key
-- 例外存 'YYYY-MM'（如 '2025-01'）——兩種格式固定寬度，字串排序皆等於時間排序，
-- 沿用同一張表同一套邏輯，不為月頻資料另開表（見程式碼 healthcheck 套件註解）。
CREATE TABLE stock_health_snapshot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_id     VARCHAR(10)    NOT NULL,
    quarter      VARCHAR(10)    NOT NULL,
    metric_key   VARCHAR(50)    NOT NULL,
    value        NUMERIC(18, 4),
    note         TEXT,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by   VARCHAR(50)    NOT NULL,
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_by   VARCHAR(50)    NOT NULL,
    CONSTRAINT pk_stock_health_snapshot PRIMARY KEY (id),
    CONSTRAINT fk_stock_health_snapshot_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id),
    CONSTRAINT uq_stock_health_snapshot UNIQUE (stock_id, quarter, metric_key)
);

-- 支援「近五季」查詢：給定股票+細項，依 quarter 倒序取最近幾筆
CREATE INDEX idx_stock_health_snapshot_stock_metric ON stock_health_snapshot (stock_id, metric_key, quarter DESC);
