-- DB-01: initial schema for the stock target price screen.
-- See docs/spec/DB-01-database-schema.md for the full design rationale (DEC-17~25).
--
-- Every table carries the standard audit columns created_at/created_by/updated_at/updated_by
-- (DEC-25). updated_at/updated_by are expected to be maintained by the application layer
-- (JPA @CreationTimestamp / @UpdateTimestamp style), not by a DB trigger.

CREATE TABLE stock (
    stock_id           VARCHAR(10)   NOT NULL,
    stock_name         VARCHAR(100)  NOT NULL,
    industry_category  VARCHAR(100),
    market_type        VARCHAR(20),
    latest_close_price NUMERIC(12, 4),
    latest_price_date  DATE,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by         VARCHAR(50)   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by         VARCHAR(50)   NOT NULL,
    CONSTRAINT pk_stock PRIMARY KEY (stock_id)
);

CREATE TABLE stock_price_yearly (
    stock_id         VARCHAR(10)   NOT NULL,
    year             INTEGER       NOT NULL,
    avg_close_price  NUMERIC(12, 4) NOT NULL,
    high_price       NUMERIC(12, 4) NOT NULL,
    low_price        NUMERIC(12, 4) NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by       VARCHAR(50)   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by       VARCHAR(50)   NOT NULL,
    CONSTRAINT pk_stock_price_yearly PRIMARY KEY (stock_id, year),
    CONSTRAINT fk_stock_price_yearly_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id)
);

CREATE TABLE stock_valuation_yearly (
    stock_id           VARCHAR(10)   NOT NULL,
    year               INTEGER       NOT NULL,
    avg_per            NUMERIC(10, 4),
    low_per            NUMERIC(10, 4),
    high_per           NUMERIC(10, 4),
    avg_pbr            NUMERIC(10, 4),
    low_pbr            NUMERIC(10, 4),
    high_pbr           NUMERIC(10, 4),
    avg_dividend_yield NUMERIC(10, 4),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by         VARCHAR(50)   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by         VARCHAR(50)   NOT NULL,
    CONSTRAINT pk_stock_valuation_yearly PRIMARY KEY (stock_id, year),
    CONSTRAINT fk_stock_valuation_yearly_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id)
);

CREATE TABLE stock_financial_statement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_id       VARCHAR(10)    NOT NULL,
    statement_date DATE           NOT NULL,
    type           VARCHAR(50)    NOT NULL,
    value          NUMERIC(18, 4) NOT NULL,
    origin_name    VARCHAR(100),
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by     VARCHAR(50)    NOT NULL,
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_by     VARCHAR(50)    NOT NULL,
    CONSTRAINT pk_stock_financial_statement PRIMARY KEY (id),
    CONSTRAINT fk_stock_financial_statement_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id),
    CONSTRAINT uq_stock_financial_statement UNIQUE (stock_id, statement_date, type)
);

CREATE TABLE stock_dividend (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_id                       VARCHAR(10) NOT NULL,
    year                           INTEGER     NOT NULL,
    cash_earnings_distribution     NUMERIC(10, 4),
    cash_statutory_surplus         NUMERIC(10, 4),
    cash_ex_dividend_trading_date  DATE,
    cash_dividend_payment_date     DATE,
    stock_earnings_distribution    NUMERIC(10, 4),
    stock_statutory_surplus        NUMERIC(10, 4),
    stock_ex_dividend_trading_date DATE,
    announcement_date              DATE        NOT NULL,
    created_at                     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                     VARCHAR(50) NOT NULL,
    updated_at                     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by                     VARCHAR(50) NOT NULL,
    CONSTRAINT pk_stock_dividend PRIMARY KEY (id),
    CONSTRAINT fk_stock_dividend_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id),
    CONSTRAINT uq_stock_dividend UNIQUE (stock_id, year, announcement_date)
);

CREATE TABLE finmind_sync_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_id       VARCHAR(10) NOT NULL,
    dataset        VARCHAR(50) NOT NULL,
    last_data_date DATE,
    status         VARCHAR(20) NOT NULL DEFAULT 'ok',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by     VARCHAR(50) NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by     VARCHAR(50) NOT NULL,
    CONSTRAINT pk_finmind_sync_log PRIMARY KEY (id),
    CONSTRAINT fk_finmind_sync_log_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id),
    CONSTRAINT uq_finmind_sync_log UNIQUE (stock_id, dataset)
);

CREATE TABLE stock_target_price_setting (
    stock_id            VARCHAR(10) NOT NULL,
    investment_strategy TEXT,
    eps_avg_years       SMALLINT    NOT NULL DEFAULT 5,
    bps_avg_years       SMALLINT    NOT NULL DEFAULT 5,
    setting_note        TEXT,
    target_price_level  SMALLINT    NOT NULL DEFAULT 3,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          VARCHAR(50) NOT NULL,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          VARCHAR(50) NOT NULL,
    CONSTRAINT pk_stock_target_price_setting PRIMARY KEY (stock_id),
    CONSTRAINT fk_stock_target_price_setting_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id),
    CONSTRAINT chk_eps_avg_years CHECK (eps_avg_years IN (3, 5, 10)),
    CONSTRAINT chk_bps_avg_years CHECK (bps_avg_years IN (3, 5, 10)),
    CONSTRAINT chk_target_price_level CHECK (target_price_level BETWEEN 1 AND 6)
);

CREATE TABLE stock_ai_suggestion (
    stock_id        VARCHAR(10) NOT NULL,
    suggestion_text TEXT,
    model_name      VARCHAR(50),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by      VARCHAR(50) NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by      VARCHAR(50) NOT NULL,
    CONSTRAINT pk_stock_ai_suggestion PRIMARY KEY (stock_id),
    CONSTRAINT fk_stock_ai_suggestion_stock FOREIGN KEY (stock_id) REFERENCES stock (stock_id)
);

-- Supports the "上次更新時間" MIN(updated_at) lookup across datasets for a given stock (SA-01 DEC-19)
CREATE INDEX idx_finmind_sync_log_stock_id ON finmind_sync_log (stock_id);
